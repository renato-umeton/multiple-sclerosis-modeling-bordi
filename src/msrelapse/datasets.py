"""The synthetic twin of the 2013 cohort, its provenance and the closing table.

The clinical records of Bordi et al. 2013 were never released: section 14 of
``docs/paper_facts.md`` records that the article carries no data availability
statement, no supplementary material and no deposited series. What this package
ships instead is a synthetic twin, three files of 70 records generated by
:func:`msrelapse.cohort.generate` from the numbers the article prints, in the
three schemas of :mod:`msrelapse.io`. :func:`provenance` says so in full, and
:func:`load_synthetic_bordi2013` puts the first line of it on the frame it
returns.

The twin is not the cohort of the study and no clinical claim can be read off
it. What it is for is the closing table of :func:`reproduction_table`, which
takes a weekly record and measures on it, the way the paper measured its own,
every aggregate the article reports: the two mean durations, the three ranges,
the barrier ratio of equation (7), and the two qualitative claims the article
makes without a test. A reader who obtains the real series from the
corresponding authors can run the same function on it and read the same table.

References
----------
I. Bordi, R. Umeton, V. A. G. Ricigliano, et al., "A mechanistic, stochastic
model helps understand multiple sclerosis course and pathogenesis",
International Journal of Genomics, 2013, doi 10.1155/2013/910321.
"""

from __future__ import annotations

from importlib import resources
from pathlib import Path
from typing import TYPE_CHECKING, Final, get_args

import pandas as pd

from msrelapse import fit
from msrelapse._params import PAPER
from msrelapse.cohort import bordi2013_spec, generate
from msrelapse.io import (
    Schema,
    read_durations,
    read_events,
    read_weekly,
    weekly_to_durations,
    write_csv,
)
from msrelapse.model import barrier_ratio_from_durations

if TYPE_CHECKING:  # pragma: no cover - the names are needed only by the type checker
    from collections.abc import Mapping
    from importlib.resources.abc import Traversable

__all__ = [
    "SYNTHETIC_SEED",
    "load_synthetic_bordi2013",
    "provenance",
    "regenerate_synthetic_bordi2013",
    "reproduction_table",
]

SYNTHETIC_SEED: Final = 20130910
"""Seed the shipped files were generated from.

It opens with the year of the volume the article appeared in, which
``docs/paper_facts.md`` records, and closes with four arbitrary digits, so that
the number is memorable. The article carries no issue date and none is claimed
here.
"""

_DATA_PACKAGE: Final = "msrelapse"
_DATA_DIRECTORY: Final = "data"
_PROVENANCE_FILE: Final = "PROVENANCE.txt"
_STEM: Final = "synthetic_bordi2013"

# The three schema names, taken from the type rather than written out again, so
# that this module cannot drift from :data:`msrelapse.io.Schema`.
_SCHEMAS: Final = get_args(Schema)

_NO_HEALTH: Final = PAPER.state_no_health.value
_HEALTH: Final = PAPER.state_health.value

# Significance level the three p value rows are judged at when the caller names
# none, the two goodness of fit rows and the periodicity row, the conventional
# one.
_DEFAULT_ALPHA: Final = 0.05

# Tolerances of the two mean duration rows, each as a fraction of the printed
# value, and what a cohort of seventy records can do against them. Regenerating
# the twin under the sixty consecutive seeds from SYNTHETIC_SEED and applying
# each rule to the cohort it gives: the five percent relapse rule is met on 36 of
# the 60, the ten percent remission rule on 52, and every rule of the table at
# once on 27, which is a little under half. Neither number is a fault of the
# pipeline, it is the size of the cohort. The twin holds 261 relapse runs and 261
# remission runs, and one standard error of their means is 5.8 percent of the
# relapse mean and 6.3 percent of the remission mean, so the five percent bound
# is narrower than one standard error and the ten percent bound is about one and
# a half of them. Both values are kept, because the plan fixes them and they are
# the right bounds to want; what a False row under another seed measures is the
# sampling noise of seventy records.
_RELAPSE_MEAN_TOLERANCE: Final = 0.05
_REMISSION_MEAN_TOLERANCE: Final = 0.10

# The article gives its relapse maximum as "about 24 weeks" and its remission
# maximum as "about 1000 weeks in exceptional cases", so both are read as orders
# of magnitude rather than as bounds: the table asks for containment on one side
# and an order of magnitude on the other. The six weeks of headroom above the
# printed relapse maximum leave the row a containment check with a tail in it.
# Over the same sixty seeds the longest relapse of the twin ran 16 to 35 weeks
# and cleared the 30 week ceiling on six of them, so about one verdict in ten on
# that row is decided by the tail rather than by the pipeline: a geometric of
# mean 4.34 weeks puts about four parts in ten thousand of its mass above 30
# weeks, and a cohort of this size holds about 260 relapses.
_RELAPSE_MAX_HEADROOM: Final = 6.0
_REMISSION_MAX_FLOOR: Final = 0.1
_REMISSION_MAX_CEILING: Final = 3.0

# The top bin edge of Figure 3 sits one week above the printed maximum of the
# relapsing-remitting phase, 1312 against 1311, and
# :func:`msrelapse.cohort.generate` rounds a drawn window up to whole weeks, so a
# draw inside that last week is recorded as a 1312 week record and misses the
# printed maximum by exactly one week. That happens to about one patient in four
# thousand, which is about one cohort of seventy in fifty-five, and the row would
# then report a failure that says nothing about the twin. The rule therefore
# carries the week the top edge adds and its tolerance text says so. The maximum
# keeps this a headroom and never a tightening: if a later reading of Figure 3
# put its top edge at or below the printed maximum, the rule would stay the
# printed one.
_PHASE_MAX_HEADROOM: Final = max(
    0.0, PAPER.fig3_bin_edges_weeks.value[-1] - PAPER.rr_phase_max_weeks.value
)

# Absolute tolerance on the barrier ratio of equation (7). The ratio is built
# from the two mean durations above and inherits the error of both, and three
# numbers say how tight a bound on it can honestly be:
#
#   * the two tolerances above, five percent on the relapse mean and ten percent
#     on the remission mean, propagate through the ratio of two logarithms to
#     0.177;
#   * one standard error of the two measured means, over the 261 relapse runs
#     and 261 remission runs those records hold, propagates to 0.128;
#   * the article itself prints 3.1 for a value its own two durations put at
#     3.157, an error of 0.057.
#
# The bound is set above all three. A bound of 0.05 would be tighter than the
# article's own rounding and well inside the sampling error of a cohort of this
# size: the relapse mean drives the ratio, its standard error alone moves the
# ratio by 0.120, and pushing that below 0.05 takes about 1500 relapse runs,
# which is close to six times the cohort of the paper. On seventy records a
# bound of 0.05 could only be met by choosing a seed that happens to meet it,
# which would say nothing about the pipeline. The same sixty seed sweep bears
# that out: the gap lands within 0.05 on 13 of the 60 seeds and within 0.2 on 53,
# with a median of 0.097 and a largest of 0.313. A reader who wants the tighter
# comparison should build the table on a larger cohort.
_BARRIER_RATIO_TOLERANCE: Final = 0.2

# Seed of the parametric bootstrap behind the two Kolmogorov-Smirnov rows when
# the caller names no generator, so that one record gives one table. It reuses
# the seed of the cohort only so that this module carries one number rather than
# two; nothing couples the two, and a caller who wants the bootstrap drawn from
# somewhere else passes an rng of their own.
_KS_SEED: Final = SYNTHETIC_SEED

# The reading of memorylessness the two goodness of fit rows report, which is
# also the reading a precomputed test has to carry.
_KS_METHOD: Final = "ks"

_TABLE_COLUMNS: Final = ("quantity", "paper", "reproduced", "tolerance", "within_tolerance")


def _data_file(name: str) -> Traversable:
    """Return the shipped file of a given name, wherever the package is installed.

    Parameters
    ----------
    name : str
        Base name of the file inside the data directory of the package.

    Returns
    -------
    importlib.resources.abc.Traversable
        The file, which may live inside an archive rather than on disk.
    """
    return resources.files(_DATA_PACKAGE).joinpath(_DATA_DIRECTORY, name)


def _csv_name(schema: Schema) -> str:
    """Return the file name of one shipped schema.

    Parameters
    ----------
    schema : {'weekly', 'durations', 'events'}
        Which of the three files is wanted.

    Returns
    -------
    str
        The base name of that file.

    Raises
    ------
    ValueError
        If `schema` is not one of the three names.
    """
    if schema not in _SCHEMAS:
        raise ValueError(f"schema must be one of {_SCHEMAS}, got {schema!r}")
    return f"{_STEM}_{schema}.csv"


def provenance() -> str:
    """Return the full provenance note that travels with the shipped files.

    Returns
    -------
    str
        The text of ``PROVENANCE.txt``, which names the generator, the seed, the
        generative durations, the size of the cohort, how to regenerate the
        files and where the real series may be requested.

    Examples
    --------
    >>> "synthetic" in provenance().lower()
    True
    """
    return _data_file(_PROVENANCE_FILE).read_text(encoding="utf-8")


def load_synthetic_bordi2013(schema: Schema = "weekly") -> pd.DataFrame:
    """Read one of the three shipped files and validate it against its schema.

    Parameters
    ----------
    schema : {'weekly', 'durations', 'events'}, optional
        Which shape of the same 70 records to read.

    Returns
    -------
    pandas.DataFrame
        The records, with the columns of that schema in schema order. The frame
        carries the first line of :func:`provenance` in
        ``frame.attrs['provenance']``.

    Raises
    ------
    ValueError
        If `schema` is not one of the three names, or if the shipped file does
        not obey the schema it claims.

    Notes
    -----
    ``attrs`` is metadata that pandas propagates through some operations and
    drops in others: a ``groupby`` or a merge usually loses it, and a slice
    usually keeps it. Read it off the frame this returns rather than off one
    derived from it, and call :func:`provenance` for the full note, which is
    never attached to anything.

    Examples
    --------
    >>> frame = load_synthetic_bordi2013()
    >>> frame["patient_id"].nunique() == PAPER.n_patients.value
    True
    """
    name = _csv_name(schema)
    with resources.as_file(_data_file(name)) as path:
        if schema == "weekly":
            frame = read_weekly(path)
        elif schema == "durations":
            frame = read_durations(path)
        else:
            frame = read_events(path)
    frame.attrs["provenance"] = provenance().splitlines()[0]
    return frame


def regenerate_synthetic_bordi2013(
    out_dir: str | Path | None = None,
    seed: int = SYNTHETIC_SEED,
) -> dict[str, Path]:
    """Generate the three shipped files again and write them out.

    The cohort is ``generate(bordi2013_spec("renewal"), rng=seed)``, which is
    exactly the call the shipped files came from, so running this with the
    default arguments into the data directory of the package rewrites those
    files with the same bytes.

    Parameters
    ----------
    out_dir : str or pathlib.Path, optional
        Directory to write into, created if it does not exist. The default is
        the data directory of the installed package, which is refused for any
        seed but :data:`SYNTHETIC_SEED`.
    seed : int, optional
        Seed of the cohort. The default is :data:`SYNTHETIC_SEED`.

    Returns
    -------
    dict of str to pathlib.Path
        The path written for each of the three schemas, keyed by schema name.

    Raises
    ------
    ValueError
        If `seed` is not :data:`SYNTHETIC_SEED` and no `out_dir` is named, since
        a cohort under another seed is not the shipped twin and overwriting the
        shipped files with it would leave three files that ``PROVENANCE.txt``,
        :data:`SYNTHETIC_SEED` and the closing table no longer describe. Or if
        the generated cohort holds no weekly record, which cannot happen for the
        spec of the paper and is checked so that a future change to that spec
        fails here rather than writing an empty file.

    Notes
    -----
    The default directory is found from the location of this module rather than
    through :mod:`importlib.resources`, which is how the files are read. The two
    agree for an ordinary installation, which is the only one a file can be
    written into at all: a package imported out of a zip archive or a wheel has
    nowhere to put the result, and a caller in that position has to name an
    `out_dir` of their own.
    """
    if out_dir is None and seed != SYNTHETIC_SEED:
        raise ValueError(
            f"seed {seed!r} is not {SYNTHETIC_SEED}, the seed of the shipped twin, so the "
            f"cohort it generates is not the twin the provenance note and the closing table "
            f"describe; give it an out_dir of its own rather than letting it overwrite the "
            f"three files in the data directory of the package"
        )
    cohort = generate(bordi2013_spec("renewal"), rng=seed)
    if cohort.weekly is None or cohort.durations is None:
        raise ValueError(
            "the cohort of bordi2013_spec produced no weekly record, so the durations file "
            "cannot be written; the spec has to keep weekly=True for the shipped twin"
        )
    directory = Path(__file__).parent / _DATA_DIRECTORY if out_dir is None else Path(out_dir)
    directory.mkdir(parents=True, exist_ok=True)
    frames: dict[Schema, pd.DataFrame] = {
        "weekly": cohort.weekly,
        "durations": cohort.durations,
        "events": cohort.events,
    }
    written: dict[str, Path] = {}
    for schema, frame in frames.items():
        path = directory / _csv_name(schema)
        write_csv(frame, path)
        written[schema] = path
    return written


def reproduction_table(
    weekly: pd.DataFrame,
    alpha: float | None = None,
    rng: fit.Seed = None,
    ks_tests: Mapping[int, fit.TestResult] | None = None,
    periodicity: fit.PeriodicityResult | None = None,
) -> pd.DataFrame:
    """Measure on a weekly record every aggregate the article reports.

    Each row puts the number the article prints beside the number this record
    gives, the rule the two are compared under and whether the rule is met.
    Every printed number comes from :data:`msrelapse._params.PAPER`, and every
    mean is the naive one, over every recorded run of a state with no censoring
    correction, because that is how the paper computed its own.

    Parameters
    ----------
    weekly : pandas.DataFrame
        A frame in the weekly schema of :mod:`msrelapse.io`. It is validated
        before use.
    alpha : float, optional
        Significance level the three p value rows are judged at, the two
        goodness of fit rows and the periodicity row. The default of None uses
        0.05.
    rng : numpy.random.Generator or int or None, optional
        Generator behind the parametric bootstrap of the two goodness of fit
        rows, or a seed for :func:`numpy.random.default_rng`. The default of
        None draws from the seed this module fixes, so that one record gives one
        table when no generator is named. It is also handed to
        :func:`msrelapse.fit.test_periodicity`, whose Fisher g test is exact and
        draws nothing, so the two goodness of fit rows are the only rows that
        move with it.
    ks_tests : mapping of int to msrelapse.fit.TestResult, optional
        The Kolmogorov-Smirnov reading of each state, keyed by clinical code,
        already measured on the durations of this same record. A caller that
        needs the statistic and the sample size beside the p value, which no row
        of this table carries, measures the test once and hands it in here rather
        than leaving the table to draw a second bootstrap of its own. The default
        of None measures both tests here.
    periodicity : msrelapse.fit.PeriodicityResult, optional
        The pooled search for a period, already measured on this same record, for
        a caller that needs the per patient table beside the pooled p value. The
        default of None measures it here.

    Returns
    -------
    pandas.DataFrame
        One row per reported quantity, with the columns ``quantity``,
        ``paper``, ``reproduced``, ``tolerance`` and ``within_tolerance``. A
        range is held as a tuple of two floats. ``paper`` is None where the
        article reports nothing, and ``tolerance`` and ``within_tolerance`` are
        None where no rule applies.

    Raises
    ------
    ValueError
        If `weekly` does not obey the weekly schema, if it holds no run of one
        of the two states, or if `alpha` is not strictly between 0 and 1. Two
        rows carry a requirement of their own on top of that, and a short record
        meets both easily: the goodness of fit rows need at least two complete,
        uncensored durations of each state, and the periodicity row needs at
        least one patient whose periodogram the pooled test can read, which asks
        for eight weeks of follow up, three relapse onsets and onsets that do
        not fall in every other week. The table is a cohort measurement; a
        handful of records does not carry it.

        A precomputed result is checked against the record before it is
        reported, since a stale one would put a p value in the table that
        belongs to no record in it: `ks_tests` has to hold a Kolmogorov-Smirnov
        reading of each state over exactly the complete durations this record
        holds, and `periodicity` has to have been measured on exactly these
        patients.

    Notes
    -----
    The barrier ratio row is judged against what equation (7) gives for the two
    durations the article prints, which
    :func:`msrelapse.model.barrier_ratio_from_durations` recomputes, and not
    against the rounded ratio the article prints beside them. Its tolerance,
    ``_BARRIER_RATIO_TOLERANCE``, is deliberately loose, because the ratio is
    built from two mean durations and inherits the error of both: on a cohort of
    the size of the study, one standard error of the two means already moves it
    by about 0.13, and the tolerances of the two mean rows above propagate to
    about 0.18. A bound as tight as 0.05 needs a cohort several times larger than
    the seventy records the article followed, whatever the pipeline does; the
    source of this module carries the measurement beside the constant.

    That row is the only barrier ratio row of the table, and the three worked
    examples of Section 3.4 are deliberately not rows of it. The ratios of
    patients 23, 32 and 53 are read off the durations the article prints for
    each of them and not off any record, so there is nothing in a weekly frame
    to put beside them: the twin holds no counterpart of those three patients,
    and a real series obtained from the corresponding authors would number its
    own. :func:`msrelapse.cohort.paper_patients` recomputes the three from the
    printed durations, one row per patient, which is where that comparison
    belongs.

    How often the whole table comes out True is worth knowing before reading one:
    not every time. Regenerating the twin under the sixty consecutive seeds from
    :data:`SYNTHETIC_SEED` and building this table on each of the sixty cohorts,
    every judged row is True on 27 of them. The five percent relapse mean row is
    the one that fails most often, on 24 of the 60, and the ten percent remission
    mean row on 8, the barrier ratio row on 7, the relapse range row on 6 and the
    remission goodness of fit row on 1; the two remaining range rows, the relapse
    goodness of fit row and the periodicity row are True on all sixty. A
    False row is therefore the sampling noise of seventy records rather than a
    fault of the pipeline that built them, and the source of this module carries
    the sweep beside each tolerance it belongs to. The
    shipped twin is the first cohort of that sweep, the one :data:`SYNTHETIC_SEED`
    names and the one the provenance note describes: on it the relapse mean lands
    4.2 percent below the printed value and the remission mean 4.3 percent above
    it.

    Three rows are not comparisons with a printed number, because the article
    prints none: section 7 of ``docs/paper_facts.md`` records that it reports no
    fit, no test and no interval anywhere, and that its exponential and
    no-periodicity claims rest on the shape of two histograms. Their ``paper``
    entry is therefore None, and they are read as follows.

    The two Kolmogorov-Smirnov rows are judged, at `alpha`, against the claim the
    article makes in prose: that the durations of each state carry no typical
    scale. The p value is the parametric bootstrap of
    :func:`msrelapse.fit.test_memoryless`, drawn from `rng` and from the seed
    this module fixes when the caller names none, and a p value above `alpha`
    means the record is consistent with a memoryless duration rather than that it
    is one. It is a Monte Carlo estimate, so it moves a little with the
    generator: on the shipped twin the relapse row lands between about 0.50 and
    0.56 over the first few seeds, well clear of any level a reader would judge
    it at.

    The periodicity row is judged at `alpha` in the same way, against the
    article's other claim in prose: that the relapses carry no typical period.
    The p value is the pooled Fisher g test of
    :func:`msrelapse.fit.test_periodicity`, read on the relapse onsets of every
    patient rather than on the +1 and -1 state series, because the onsets of a
    memoryless record have the flat spectrum the g test compares against while
    the state series does not. A p value above `alpha` means the record leaves
    the claim of the article standing, not that no rhythm exists.

    That row says little about the shipped twin, and its own figures say how
    little: 29 of the 70 records carry fewer than three relapse onsets and are
    skipped, 28 of the 41 that are read give a per patient p value of exactly 1,
    the smallest of the 41 is 0.24, and the pooled value is 1.0. At about four
    onsets per record, that is what a test of almost no power returns rather than
    a measurement of the cohort; the Notes of
    :func:`msrelapse.fit.test_periodicity` carry the measured size at a handful
    of onsets. Putting the claim of the article at any risk needs records
    followed for longer, not a rule written more tightly.

    None of the three says more than a goodness of fit p value can. Failing to
    reject is not evidence of the null, and a cohort of seventy records is not
    a large sample; read the three rows as the record declining to contradict
    the article rather than as a confirmation of it.

    Examples
    --------
    >>> table = reproduction_table(load_synthetic_bordi2013())
    >>> table["quantity"].iloc[0]
    'mean relapse duration (weeks)'
    """
    level = _DEFAULT_ALPHA if alpha is None else alpha
    if not 0.0 < level < 1.0:
        raise ValueError(f"alpha must lie strictly between 0 and 1, got {alpha!r}")
    runs = weekly_to_durations(weekly)
    relapses = runs.loc[runs["state"] == _NO_HEALTH, "duration_w"]
    remissions = runs.loc[runs["state"] == _HEALTH, "duration_w"]
    if relapses.empty or remissions.empty:
        raise ValueError(
            f"the record holds {relapses.size} relapse run(s) and {remissions.size} remission "
            f"run(s), so the table has no mean duration to report for one of the two states"
        )
    if ks_tests is not None:
        _check_ks_tests(ks_tests, runs)
    if periodicity is not None:
        _check_periodicity(periodicity, weekly)
    generator = _KS_SEED if rng is None else rng
    phase = weekly.groupby("patient_id", sort=True).size()
    rows = [
        *_duration_rows(relapses, remissions),
        *_range_rows(relapses, remissions, phase),
        _barrier_ratio_row(runs),
        *_memoryless_rows(runs, level, generator, ks_tests),
        _periodicity_row(weekly, level, generator, periodicity),
    ]
    # Column by column and as object, so that a column holding both a value and
    # a None keeps the None rather than turning it into a missing float, and so
    # that the two columns holding a pair of weeks can hold the pair.
    columns = zip(*rows, strict=True)
    return pd.DataFrame(
        {
            name: pd.Series(list(values), dtype=object)
            for name, values in zip(_TABLE_COLUMNS, columns, strict=True)
        }
    )


def _row(
    quantity: str,
    paper: object,
    reproduced: object,
    tolerance: str | None = None,
    within_tolerance: bool | None = None,
) -> tuple[str, object, object, str | None, bool | None]:
    """Return one row of the closing table.

    Parameters
    ----------
    quantity : str
        Name of the reported quantity, with its unit.
    paper : object
        What the article prints, or None where it prints nothing.
    reproduced : object
        What the record gives.
    tolerance : str, optional
        The rule the two are compared under, in words, or None where there is
        none.
    within_tolerance : bool, optional
        Whether the rule is met, or None where there is no rule.

    Returns
    -------
    tuple
        The five fields of the row, in the order of :data:`_TABLE_COLUMNS`.
    """
    return quantity, paper, reproduced, tolerance, within_tolerance


def _duration_rows(
    relapses: pd.Series[int],
    remissions: pd.Series[int],
) -> list[tuple[str, object, object, str | None, bool | None]]:
    """Return the two mean duration rows of the table.

    Parameters
    ----------
    relapses : pandas.Series
        Every recorded relapse duration, in whole weeks.
    remissions : pandas.Series
        Every recorded remission duration, in whole weeks, censored ones
        included as the paper included them.

    Returns
    -------
    list of tuple
        The relapse mean row and the remission mean row.
    """
    printed_relapse = PAPER.tau_no_health_cohort_weeks.value
    printed_remission = PAPER.tau_health_cohort_weeks.value
    measured_relapse = float(relapses.mean())
    measured_remission = float(remissions.mean())
    return [
        _row(
            "mean relapse duration (weeks)",
            printed_relapse,
            measured_relapse,
            f"{_RELAPSE_MEAN_TOLERANCE:.0%} of the printed value",
            _within_fraction(measured_relapse, printed_relapse, _RELAPSE_MEAN_TOLERANCE),
        ),
        _row(
            "mean remission duration (weeks)",
            printed_remission,
            measured_remission,
            f"{_REMISSION_MEAN_TOLERANCE:.0%} of the printed value",
            _within_fraction(measured_remission, printed_remission, _REMISSION_MEAN_TOLERANCE),
        ),
    ]


def _range_rows(
    relapses: pd.Series[int],
    remissions: pd.Series[int],
    phase: pd.Series[int],
) -> list[tuple[str, object, object, str | None, bool | None]]:
    """Return the three range rows of the table.

    Parameters
    ----------
    relapses : pandas.Series
        Every recorded relapse duration, in whole weeks.
    remissions : pandas.Series
        Every recorded remission duration, in whole weeks.
    phase : pandas.Series
        The length of each patient's record, in whole weeks.

    Returns
    -------
    list of tuple
        The relapse range row, the remission maximum row and the
        relapsing-remitting phase range row.
    """
    relapse_floor = PAPER.relapse_duration_min_weeks.value
    relapse_ceiling = PAPER.relapse_duration_max_weeks.value
    remission_ceiling = PAPER.remission_duration_max_weeks.value
    phase_floor = PAPER.rr_phase_min_weeks.value
    phase_ceiling = PAPER.rr_phase_max_weeks.value
    relapse_span = (float(relapses.min()), float(relapses.max()))
    remission_max = float(remissions.max())
    phase_span = (float(phase.min()), float(phase.max()))
    headroom = relapse_ceiling + _RELAPSE_MAX_HEADROOM
    phase_headroom = phase_ceiling + _PHASE_MAX_HEADROOM
    return [
        _row(
            "relapse duration range (weeks)",
            (relapse_floor, relapse_ceiling),
            relapse_span,
            f"shortest at least {relapse_floor:g} and longest at most {headroom:g} weeks",
            bool(relapse_span[0] >= relapse_floor and relapse_span[1] <= headroom),
        ),
        _row(
            "longest remission (weeks)",
            remission_ceiling,
            remission_max,
            f"between {_REMISSION_MAX_FLOOR:g} and {_REMISSION_MAX_CEILING:g} times the "
            f"printed value, an order of magnitude",
            bool(
                _REMISSION_MAX_FLOOR * remission_ceiling
                <= remission_max
                <= _REMISSION_MAX_CEILING * remission_ceiling
            ),
        ),
        _row(
            "relapsing-remitting phase range (weeks)",
            (phase_floor, phase_ceiling),
            phase_span,
            f"inside {phase_floor:g} to {phase_headroom:g} weeks by inclusion, the printed "
            f"range plus the {_PHASE_MAX_HEADROOM:g} week the top bin edge of Figure 3 sits "
            f"above the printed maximum; the range is a property of the follow up windows and "
            f"is exact only for the real series",
            bool(phase_span[0] >= phase_floor and phase_span[1] <= phase_headroom),
        ),
    ]


def _barrier_ratio_row(runs: pd.DataFrame) -> tuple[str, object, object, str | None, bool | None]:
    """Return the barrier ratio row of the table.

    Parameters
    ----------
    runs : pandas.DataFrame
        A frame in the durations schema.

    Returns
    -------
    tuple
        The row, comparing equation (7) on this record with equation (7) on the
        two durations the article prints, which is 3.157 and not the 3.1 the
        article rounds it to.
    """
    printed = PAPER.barrier_ratio_cohort.value
    recomputed = barrier_ratio_from_durations(
        PAPER.tau_health_cohort_weeks.value, PAPER.tau_no_health_cohort_weeks.value
    )
    measured = fit.barrier_ratio(runs)
    return _row(
        "barrier ratio dV1/dV2, equation (7)",
        printed,
        measured,
        f"within {_BARRIER_RATIO_TOLERANCE:g} of {recomputed:.3f}, the value the printed "
        f"durations imply",
        bool(abs(measured - recomputed) <= _BARRIER_RATIO_TOLERANCE),
    )


def _complete_durations(runs: pd.DataFrame, state: int) -> int:
    """Return how many complete durations of one state a durations frame holds.

    Parameters
    ----------
    runs : pandas.DataFrame
        A frame in the durations schema.
    state : int
        The clinical code of the state to count.

    Returns
    -------
    int
        The number of runs of that state that were not cut short by the end of
        follow up, which is the sample :func:`msrelapse.fit.test_memoryless`
        reads.
    """
    return int(((runs["state"] == state) & ~runs["censored"]).sum())


def _check_ks_tests(ks_tests: Mapping[int, fit.TestResult], runs: pd.DataFrame) -> None:
    """Raise unless a precomputed pair of tests belongs to this record.

    Parameters
    ----------
    ks_tests : mapping of int to msrelapse.fit.TestResult
        What the caller handed in.
    runs : pandas.DataFrame
        The durations of the record the table is being built on.

    Raises
    ------
    ValueError
        If a state is missing, if a result is a reading of another kind, or if a
        result was measured on a different number of durations than this record
        holds, which is a result that does not belong to it.
    """
    for state in (_NO_HEALTH, _HEALTH):
        result = ks_tests.get(state)
        if result is None:
            raise ValueError(
                f"ks_tests holds no test of state {state:+d}, and the closing table reports "
                f"one goodness of fit row per state; pass a {_KS_METHOD!r} test of each or "
                f"none at all"
            )
        if result.method != _KS_METHOD:
            raise ValueError(
                f"the test of state {state:+d} carries method {result.method!r} and the "
                f"goodness of fit row reports a {_KS_METHOD!r} p value, so the two do not "
                f"describe the same reading"
            )
        expected = _complete_durations(runs, state)
        if result.n != expected:
            raise ValueError(
                f"the test of state {state:+d} was measured on {result.n} duration(s) and this "
                f"record holds {expected} complete duration(s) of that state, so the test does "
                f"not belong to this record"
            )


def _check_periodicity(periodicity: fit.PeriodicityResult, weekly: pd.DataFrame) -> None:
    """Raise unless a precomputed periodicity result belongs to this record.

    Parameters
    ----------
    periodicity : msrelapse.fit.PeriodicityResult
        What the caller handed in.
    weekly : pandas.DataFrame
        The record the table is being built on.

    Raises
    ------
    ValueError
        If the result covers other patients than this record holds, which is a
        result measured on another record. The pooled test keeps a row for every
        patient it read, skipped ones included, so the two sets of patient
        identifiers are the same set whenever the two records are.
    """
    measured_on = sorted(str(patient) for patient in periodicity.per_patient["patient_id"])
    here = sorted(str(patient) for patient in weekly["patient_id"].unique())
    if measured_on != here:
        raise ValueError(
            f"the periodicity result names patients this record does not hold, or misses "
            f"some it does: it was measured on {len(measured_on)} patient(s) and this record "
            f"holds {len(here)}, so it belongs to another record"
        )


def _memoryless_rows(
    runs: pd.DataFrame,
    level: float,
    rng: fit.Seed,
    precomputed: Mapping[int, fit.TestResult] | None,
) -> list[tuple[str, object, object, str | None, bool | None]]:
    """Return the two exponential goodness of fit rows of the table.

    Parameters
    ----------
    runs : pandas.DataFrame
        A frame in the durations schema.
    level : float
        Significance level the two p values are judged at.
    rng : numpy.random.Generator or int or None
        Generator behind the parametric bootstrap, unused where a test is handed
        in already measured.
    precomputed : mapping of int to msrelapse.fit.TestResult or None
        The test of each state, already measured on `runs`, or None to measure
        both here. It has been checked against the record by the caller.

    Returns
    -------
    list of tuple
        One row per state, each holding the bootstrap p value of the
        Kolmogorov-Smirnov distance from a fitted exponential, judged against
        the article's claim that the durations carry no typical scale.
    """
    rows: list[tuple[str, object, object, str | None, bool | None]] = []
    for state, name in ((_NO_HEALTH, "relapse"), (_HEALTH, "remission")):
        result = (
            fit.test_memoryless(runs, state, method=_KS_METHOD, rng=rng)
            if precomputed is None
            else precomputed[state]
        )
        rows.append(
            _row(
                f"exponential fit, {name} durations (KS p value)",
                None,
                result.p_value,
                f"above alpha = {level:g}, so that the durations are not shown to depart "
                f"from the memoryless law the article describes in words",
                not result.reject(level),
            )
        )
    return rows


def _periodicity_row(
    weekly: pd.DataFrame,
    level: float,
    rng: fit.Seed,
    precomputed: fit.PeriodicityResult | None,
) -> tuple[str, object, object, str | None, bool | None]:
    """Return the periodicity row of the table.

    Parameters
    ----------
    weekly : pandas.DataFrame
        A frame in the weekly schema.
    level : float
        Significance level the pooled p value is judged at.
    rng : numpy.random.Generator or int or None
        Generator handed to the test. Fisher's g test is exact and draws
        nothing, so this row does not move with it.
    precomputed : msrelapse.fit.PeriodicityResult or None
        The search, already run on `weekly`, or None to run it here. It has been
        checked against the record by the caller.

    Returns
    -------
    tuple
        The row, holding the pooled p value of Fisher's g test over the relapse
        onsets of every patient, judged against the article's claim that the
        relapses carry no typical period.
    """
    measured = (
        fit.test_periodicity(weekly, method="fisher_g", rng=rng)
        if precomputed is None
        else precomputed
    )
    pooled = measured.pooled
    return _row(
        "periodicity of the relapse onsets (pooled Fisher g p value)",
        None,
        pooled.p_value,
        f"pooled p above alpha = {level:g}, so that no periodicity is detected, as the "
        "article reports",
        not pooled.reject(level),
    )


def _within_fraction(measured: float, printed: float, fraction: float) -> bool:
    """Return whether a measured value sits within a fraction of a printed one.

    Parameters
    ----------
    measured : float
        The value this record gives.
    printed : float
        The value the article prints.
    fraction : float
        The tolerance, as a fraction of `printed`.

    Returns
    -------
    bool
        True when the two agree to within that fraction.
    """
    return abs(measured - printed) <= fraction * abs(printed)
