def _jsonable(value: object) -> object:
    """Return one measured value in a shape ``json`` can write.

    Parameters
    ----------
    value : object
        A value of the record ``reproduce`` writes: a number, a string, a
        boolean, a tuple, a list, a dictionary or None.

    Returns
    -------
    object
        The same value, with numpy scalars turned into Python ones, tuples into
        lists and non-finite numbers into None, so that the file is valid JSON
        rather than the NaN and Infinity that ``json`` writes by default.

    Raises
    ------
    TypeError
        If `value` is of a kind this function does not know how to write, so
        that a new measurement of an unexpected kind fails here rather than
        reaching the file in a shape nothing can read back.

    Examples
    --------
    >>> _jsonable({"span": (1.0, 2.0), "missing": float("nan")})
    {'span': [1.0, 2.0], 'missing': None}
    """
    if value is None or isinstance(value, (bool, str)):
        return value
    if isinstance(value, np.generic):
        return _jsonable(value.item())
    if isinstance(value, int):
        return value
    if isinstance(value, float):
        return value if math.isfinite(value) else None
    if isinstance(value, (tuple, list)):
        return [_jsonable(item) for item in value]
    if isinstance(value, dict):
        return {str(key): _jsonable(item) for key, item in value.items()}
    raise TypeError(
        f"the reproduction record holds a {type(value).__name__} at some key, which this "
        f"module does not know how to write as JSON; add a branch to _jsonable for it"
    )


def _states(choice: str) -> tuple[int, ...]:
    """Return the clinical codes one ``--state`` argument asks for.

    Parameters
    ----------
    choice : str
        The argument, one of the two state codes written out or ``'both'``.

    Returns
    -------
    tuple of int
        The codes to work on, relapse first when both are asked for.

    Examples
    --------
    >>> _states("both") == (PAPER.state_no_health.value, PAPER.state_health.value)
    True
    """
    if choice == _BOTH_STATES:
        return _STATES
    return (int(choice),)


def _state_name(state: int) -> str:
    """Return the clinical name of one state code.

    Parameters
    ----------
    state : int
        The code, +1 for no health and -1 for health.

    Returns
    -------
    str
        ``'relapse'`` or ``'remission'``.

    Examples
    --------
    >>> _state_name(PAPER.state_health.value)
    'remission'
    """
    return "relapse" if state == _NO_HEALTH else "remission"


def _format_number(value: float) -> str:
    """Return one number at the six significant digits every printed line uses.

    Parameters
    ----------
    value : float
        The number to print.

    Returns
    -------
    str
        The number, without a trailing zero it does not need.

    Examples
    --------
    >>> _format_number(4.3), _format_number(1.0)
    ('4.3', '1')
    """
    return f"{value:.6g}"


def _format_value(value: object) -> str:
    """Return one measured value as the text a printed table holds.

    Parameters
    ----------
    value : object
        A number, a boolean, a pair of numbers, a string or None.

    Returns
    -------
    str
        The value in words: a dash where there is none, ``'yes'`` or ``'no'``
        for a verdict, and a bracketed pair for a range. A number that is not
        finite is a missing number and reads as the same dash, which is how
        ``_jsonable`` writes it to the file beside the printed table.

    Examples
    --------
    >>> _format_value(None), _format_value(True), _format_value((1.0, 24.0))
    ('-', 'yes', '(1, 24)')
    >>> _format_value(float("nan"))
    '-'
    """
    if value is None:
        return "-"
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, (tuple, list)):
        return f"({', '.join(_format_value(item) for item in value)})"
    if isinstance(value, float):
        return _format_number(value) if math.isfinite(value) else "-"
    return str(value)


