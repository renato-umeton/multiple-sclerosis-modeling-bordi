def _print_fit(label: str, result: fit.FitResult) -> None:
    """Print one fitted duration law on one line.

    Parameters
    ----------
    label : str
        What the line opens with, up to the colon.
    result : msrelapse.fit.FitResult
        The fit to print.
    """
    # The exponential family fits a rate per week; the geometric family fits a
    # per week success probability, which is a number between 0 and 1 and carries
    # no unit of its own.
    rate_unit = "per week" if result.family == _EXPONENTIAL else "per week, a probability"
    print(
        f"{label}: n={result.n} censored={result.n_censored} "
        f"mean={_format_number(result.mean)} weeks "
        f"rate={_format_number(result.rate)} {rate_unit} "
        f"ci_low={_format_number(result.ci_low)} ci_high={_format_number(result.ci_high)} "
        f"level={_format_number(result.ci_level)} method={result.ci_method} "
        f"family={result.family}"
    )


def _print_test(label: str, result: fit.TestResult) -> None:
    """Print one hypothesis test on one line.

    Parameters
    ----------
    label : str
        What the line opens with, up to the colon.
    result : msrelapse.fit.TestResult
        The test to print.
    """
    print(
        f"{label}: method={result.method} n={result.n} "
        f"statistic={_format_number(result.statistic)} p={_format_number(result.p_value)}"
    )


def _print_periodicity(result: fit.PeriodicityResult) -> None:
    """Print the pooled periodicity test and how many patients it read.

    Parameters
    ----------
    result : msrelapse.fit.PeriodicityResult
        The per patient table and the pooled test.
    """
    pooled = result.pooled
    details = pooled.details
    # Every reason a patient can be skipped for is reported by the pooled test
    # under its own n_skipped_ key, so the reasons are read off the result rather
    # than named here and one added to msrelapse.fit appears without a change.
    skipped = {
        name.removeprefix(_SKIPPED_PREFIX): int(count)
        for name, count in details.items()
        if name.startswith(_SKIPPED_PREFIX)
    }
    _print_test("pooled", pooled)
    reasons = " ".join(f"{name}={count}" for name, count in skipped.items())
    # The pooled test counts one p value per patient it could read, so its own n
    # is how many were tested, and the count below is how many there were. It is
    # read the way the reasons above are read, so that a pooled result that stops
    # reporting it prints a dash rather than failing inside a print helper.
    counted = details.get(_N_PATIENTS_KEY)
    in_record = _format_value(None if counted is None else int(counted))
    print(f"patients: in_record={in_record} tested={pooled.n} ({reasons})")


def _print_aligned(header: Sequence[str], rows: Sequence[Sequence[str]]) -> None:
    """Print a table of strings with its columns lined up under a header.

    Parameters
    ----------
    header : sequence of str
        The column names.
    rows : sequence of sequence of str
        The rows, each holding one cell per column name.
    """
    columns = zip(header, *rows, strict=True)
    widths = [max(len(cell) for cell in column) for column in columns]
    for line in (header, *rows):
        cells = (cell.ljust(width) for cell, width in zip(line, widths, strict=True))
        print("  ".join(cells).rstrip())


def _write_json(path: Path, payload: dict[str, object]) -> Path:
    """Write one record of measurements as JSON and return the file it went to.

    Parameters
    ----------
    path : pathlib.Path
        File to write.
    payload : dict
        The measurements, which are converted by ``_jsonable`` first.

    Returns
    -------
    pathlib.Path
        `path`, so that the caller can list what it wrote.
    """
