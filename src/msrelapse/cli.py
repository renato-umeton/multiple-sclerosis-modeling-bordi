def _run_reproduce(args: argparse.Namespace) -> int:
    """Measure every reported quantity on one record, write it out and report.

    Parameters
    ----------
    args : argparse.Namespace
        The parsed arguments of the ``reproduce`` subcommand.

    Returns
    -------
    int
        0 when every row of the closing table that carries a tolerance is inside
        it, and 1 otherwise.

    Raises
    ------
    ImportError
        If the figures were asked for and matplotlib is not installed. The check
        is made before the analysis rather than after it, so that an install
        without the plot extra fails in a second rather than at the end.
    """
    data: Path | None = args.data
    out: Path = args.out
    seed: int | None = args.seed
    engine: Engine | None = args.engine
    figures: bool = args.figures

    # Everything that can fail on the way out is settled before the analysis
    # starts: the directory is created and the figures are checked for, so that
    # an unwritable path or a missing matplotlib costs a second and not a whole
    # run.
    out.mkdir(parents=True, exist_ok=True)
    if figures:
        _require_matplotlib()

    # Every random draw of the run, the cohort included, comes from one seed, so
    # that a reproduction repeats itself. Without --seed that is the seed of the
    # shipped twin, which is the run this package documents its own numbers
    # against.
    effective_seed = datasets.SYNTHETIC_SEED if seed is None else seed
    # Naming either a seed or an engine asks for a cohort of this run's own;
    # naming neither reads the shipped twin, which is the cohort that seed built.
    record = _load_record(
        data,
        engine,
        generate_cohort=seed is not None or engine is not None,
        seed=effective_seed,
    )
    weekly = record.weekly
    durations = weekly_to_durations(weekly)

    fits = _duration_fits(durations)
    # Two rows of the closing table are tests this report prints in full, with
    # the statistic, the count and the per patient detail that no row can carry
    # beside the p value. They are measured here, once, and handed to the table,
    # so that the number under the table and the number inside it are one number
    # and one draw rather than two of each.
    memoryless = _memorylessness(durations, effective_seed)
    periodicity = fit.test_periodicity(weekly, method="fisher_g")
    table = datasets.reproduction_table(
        weekly,
        rng=effective_seed,
        ks_tests={state: result for state, result in memoryless if result.method == _KS_METHOD},
        periodicity=periodicity,
    )
    # The potential is calibrated to the naive means, the ones the paper itself
    # averaged and the ones the closing table compares against, rather than to
    # the censored fit, which estimates the mean of the process behind the record
    # and is the larger of the two.
    naive = {state: result for reading, state, result in fits if reading == _NAIVE_READING}
    # The control parameter is bound once and handed to the fit, so that the value
    # reported beside the asymmetry and the noise is the value they were found at.
    alpha = PAPER.alpha_reference.value
    beta, sigma = calibrate(naive[_HEALTH].mean, naive[_NO_HEALTH].mean, alpha=alpha)
    spans = _spans(table)
    ratio = _reproduced(table, _BARRIER_RATIO_QUANTITY)
    ratios = _busiest_barrier_ratios(durations)
    calibration = {"alpha": alpha, "beta": beta, "sigma": sigma}
    met = _all_within_tolerance(table)

    payload = {
        "source": record.source,
        "synthetic": record.synthetic,
        "provenance": "\n".join(record.provenance) if record.provenance else None,
        "seed": seed,
        "effective_seed": effective_seed,
        "engine": record.engine,
        "citation": _citation.short_citation(),
        # Which release wrote this directory, so that a file found later can be
        # held against the package that produced it.
        "msrelapse_version": msrelapse.__version__,
        "closing_table": table.to_dict(orient="records"),
        "all_within_tolerance": met,
        "fits": [
            {"reading": reading, "state_name": _state_name(state), **dataclasses.asdict(result)}
            for reading, state, result in fits
        ],
        "memorylessness": [
            {"state": state, "state_name": _state_name(state), **dataclasses.asdict(result)}
            for state, result in memoryless
        ],
        "periodicity": dataclasses.asdict(periodicity.pooled),
        "barrier_ratio": {"cohort": ratio, "busiest_patients": ratios},
        **spans,
        "calibration": calibration,
    }

    written = [
        _write_json(out / "numbers.json", payload),
        _write_frame(weekly, out / "weekly.csv"),
        _write_frame(durations, out / "durations.csv"),
    ]
    if figures:
        written.extend(plots.save_all_paper_figures(out, weekly, durations, rng=effective_seed))

    _report_reproduction(record, seed, effective_seed, table)
    _report_measurements(fits, memoryless, periodicity)
    _report_derived(ratio, ratios, spans, calibration)
    print()
    print(f"every judged row of the closing table within tolerance: {_format_value(met)}")
    for path in written:
        print(f"wrote {path}")
    return 0 if met else 1


def _run_simulate(args: argparse.Namespace) -> int:
    """Generate one cohort, write it in the requested schema and report.

    Parameters
    ----------
    args : argparse.Namespace
        The parsed arguments of the ``simulate`` subcommand.

    Returns
    -------
    int
        0, the cohort having been written.

    Raises
    ------
    ValueError
        If the cohort holds no frame in the requested schema.
    """
    schema: str = args.schema
    out: Path = args.out
    spec = CohortSpec(
        n=args.n,
        tau_health=args.tau_health,
        tau_relapse=args.tau_relapse,
        followup_weeks=args.weeks,
        engine=args.engine,
        alpha=args.alpha,
    )
    # The directory is created before the cohort is generated, so that an
    # unwritable or mistyped path costs a moment rather than a whole generation,
    # which under the sde engine is several seconds.
    out.parent.mkdir(parents=True, exist_ok=True)
    cohort = generate(spec, rng=args.seed)
    # The three schema names of msrelapse.io are the three frame attributes of a
    # Cohort, so the frame is read by name rather than through a map written out
    # here that a fourth schema would leave behind.
    frame: pd.DataFrame | None = getattr(cohort, schema)
    if frame is None:
        raise ValueError(
            f"the {spec.engine} engine produced no {schema} frame for this spec, so there is "
            f"nothing to write; ask for the events schema instead"
        )
    write_csv(frame, out)
    print(cohort.provenance)
    print(f"wrote {out} ({len(frame)} rows, {schema} schema)")
    return 0


def _run_fit(args: argparse.Namespace) -> int:
    """Fit the durations of each requested state and print one line per state.

    Parameters
    ----------
    args : argparse.Namespace
        The parsed arguments of the ``fit`` subcommand.

    Returns
    -------
    int
        0, every fit having been printed.
    """
    durations = read_durations(args.durations)
    for state in _states(args.state):
        result = fit.fit_durations(
            durations,
            state,
            family=args.family,
            censoring=args.censoring,
            ci=args.ci,
            bootstrap=args.bootstrap,
            continuity_correction=args.continuity_correction,
            rng=args.seed,
        )
        _print_fit(_state_name(state), result)
    return 0


def _run_test_memoryless(args: argparse.Namespace) -> int:
    """Test each requested state by each requested method and print the results.

    Parameters
    ----------
    args : argparse.Namespace
        The parsed arguments of the ``test-memoryless`` subcommand.

    Returns
    -------
    int
        0, every test having been printed.
    """
    durations = read_durations(args.durations)
    method: str = args.method
    methods = _MEMORYLESS_METHODS if method == _ALL_METHODS else (method,)
    for state in _states(args.state):
        for name in methods:
            result = fit.test_memoryless(durations, state, method=name, rng=args.seed)
            _print_test(_state_name(state), result)
    return 0


def _run_test_periodicity(args: argparse.Namespace) -> int:
    """Look for a period in a weekly record and print the pooled evidence.

    Parameters
    ----------
    args : argparse.Namespace
        The parsed arguments of the ``test-periodicity`` subcommand.

    Returns
    -------
    int
        0, the pooled test having been printed.
    """
    weekly = read_weekly(args.weekly)
    result = fit.test_periodicity(weekly, method=args.method, rng=args.seed)
    _print_periodicity(result)
    return 0


