@dataclass(frozen=True)
class _Record:
    """One weekly record together with where the CLI got it from.

    Attributes
    ----------
    weekly : pandas.DataFrame
        The record, in the weekly schema of [`msrelapse.io`][msrelapse.io].
    source : str
        One phrase naming where it came from, for the report and the file.
    synthetic : bool
        Whether the record was generated by this package rather than read from
        a file the caller named.
    provenance : tuple of str
        The lines that say so, empty when the record came from a file.
    engine : {'renewal', 'sde'} or None
        Which generator produced the record, and None when it came from a file,
        where no engine ran and the CLI has nothing to say about how the records
        were made.
    """

    weekly: pd.DataFrame
    source: str
    synthetic: bool
    provenance: tuple[str, ...]
    engine: Engine | None


def main(argv: Sequence[str] | None = None) -> int:
    """Run one subcommand and return the code the process should exit with.

    Parameters
    ----------
    argv : sequence of str, optional
        The arguments to parse, without the program name. The default of None
        reads them from ``sys.argv``.

    Returns
    -------
    int
        0 when the subcommand succeeded. ``reproduce`` returns 1 when a row of
        the closing table that carries a tolerance is outside it.

    Raises
    ------
    SystemExit
        With code 0 when ``--version`` or ``--help`` was given, which argparse
        raises once it has printed, and with code 2 when the arguments do not
        parse, which argparse raises after writing the reason to standard error.

    Examples
    --------
    >>> main(["cite", "--bibtex"])  # doctest: +ELLIPSIS
    @article{bordi2013mechanistic,
    ...
    0
    """
    parser = _build_parser()
    args = parser.parse_args(argv)
    handler: Callable[[argparse.Namespace], int] = args.handler
    return handler(args)


def _build_parser() -> argparse.ArgumentParser:
    """Return the parser of the whole command line, subcommands included.

    Returns
    -------
    argparse.ArgumentParser
        The parser. Every subparser records the function that runs it under
        ``handler``, so that [`main`][msrelapse.cli.main] never branches on the
        subcommand name.
    """
    parser = argparse.ArgumentParser(
        prog="msrelapse",
        description=(
            "Reproduce and extend the stochastic double well model of "
            "relapsing-remitting multiple sclerosis of Bordi et al. 2013."
        ),
    )
    # The installed version, printed on its own so that a reader holding a
    # reproduction directory can hold it against the msrelapse_version key
    # numbers.json carries. The action exits during parsing, before the required
    # subcommand is missed, so the flag stands on its own.
    parser.add_argument(
        "--version",
        action="version",
        version=f"msrelapse {msrelapse.__version__}",
        help="print the version of this package and exit",
    )
    subcommands = parser.add_subparsers(dest="subcommand", required=True, metavar="SUBCOMMAND")
    _add_reproduce(subcommands)
    _add_simulate(subcommands)
    _add_fit(subcommands)
    _add_test_memoryless(subcommands)
    _add_test_periodicity(subcommands)
    _add_cite(subcommands)
    _add_params(subcommands)
    return parser


def _add_reproduce(subcommands: argparse._SubParsersAction[argparse.ArgumentParser]) -> None:
    """Register the subcommand that runs the whole analysis and writes it out."""
    parser = subcommands.add_parser(
        "reproduce",
        help="run the analysis of the paper and write the numbers, records and figures",
        description=(
            "Measure on one weekly record every quantity the paper reports, write the "
            "numbers, the record and the figures to a directory, and print a table. "
            "With neither --data nor --seed nor --engine the shipped synthetic twin is "
            "read; any of the latter two generates a fresh synthetic cohort instead."
        ),
    )
    # A record read from a file was made by whatever made it, so naming an engine
    # beside it asks for something no run can deliver. The two options are refused
    # together rather than one of them being quietly ignored.
    source = parser.add_mutually_exclusive_group()
    source.add_argument(
        "--data",
        type=Path,
        default=None,
        help="weekly CSV to measure instead of the shipped synthetic twin",
    )
    source.add_argument(
        "--engine",
        choices=_ENGINES,
        default=None,
        help=f"which generator produces the cohort, not to be given with --data; an sde "
        f"cohort does not meet the closing table, so that run exits 1 as a matter of "
        f"course (default: {_RENEWAL})",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=_DEFAULT_OUT,
        help=f"directory to write into, created if it does not exist (default: {_DEFAULT_OUT})",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=None,
        help=f"seed of the generated cohort and of every bootstrap in the run, the two of "
        f"the closing table included (default: {datasets.SYNTHETIC_SEED}, the seed of the "
        f"shipped twin)",
    )
    parser.add_argument(
        "--no-figures",
        dest="figures",
        action="store_false",
        help="skip the figures, which need matplotlib",
    )
    parser.set_defaults(handler=_run_reproduce)


