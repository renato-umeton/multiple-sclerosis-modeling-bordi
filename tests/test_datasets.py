@pytest.mark.parametrize("schema", SCHEMAS)
def test_regenerating_reproduces_the_shipped_file(
    regenerated: dict[str, Path], schema: Schema
) -> None:
    # Byte for byte, not frame for frame: the files are generated by a fixed
    # seed through a fixed pipeline, so a difference in any byte is a change in
    # the twin and the shipped files have to be rewritten with it.
    #
    # The line terminator would be the one thing a checkout could change under
    # this comparison, and the ".gitattributes" at the root of the repository
    # holds it still: "*.csv text eol=lf" checks the shipped records out with a
    # single newline on every platform, including a Windows checkout, which
    # converts by default without it. msrelapse.io.write_csv writes that same
    # single newline, which is asserted below of the file this test wrote and
    # measured in tests/test_io.py, so the two sides are read exactly as they
    # are: a shipped file carrying a carriage return is a fault to report here
    # rather than something to convert away.
    path = regenerated[schema]
    written = path.read_bytes()
    assert b"\r" not in written
    assert written == shipped_bytes(path.name)


def test_regenerating_with_another_seed_gives_another_cohort(
    tmp_path: Path, regenerated: dict[str, Path]
) -> None:
    other = regenerate_synthetic_bordi2013(tmp_path, seed=SYNTHETIC_SEED + 1)
    assert other["weekly"].read_bytes() != regenerated["weekly"].read_bytes()


def test_regenerating_under_another_seed_refuses_the_shipped_directory() -> None:
    # The default directory holds the twin that the provenance note, the seed
    # constant and the closing table all describe, and a cohort under another
    # seed is not that twin. Writing it there would leave three files nothing in
    # the package describes and no way back but a checkout, so it is refused
    # rather than written.
    with pytest.raises(ValueError, match="the seed of the shipped twin"):
        regenerate_synthetic_bordi2013(seed=SYNTHETIC_SEED + 1)


def test_regenerating_refuses_a_spec_that_produces_no_weekly_record(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    # The three files are three shapes of one weekly record, so a spec that
    # produced only an events table would leave two of them unwritable. The
    # check is there so that a future edit of bordi2013_spec fails loudly here.
    def unrounded(engine: str = "renewal") -> CohortSpec:
        return CohortSpec(
            n=2, tau_health=100.0, tau_relapse=4.3, followup_weeks=300.0, weekly=False
        )

    monkeypatch.setattr(msrelapse.datasets, "bordi2013_spec", unrounded)
    with pytest.raises(ValueError, match="no weekly record"):
        regenerate_synthetic_bordi2013(tmp_path)


def one_record(patient: str, weeks: int) -> pd.DataFrame:
    """Return one weekly record of a given length, two relapse weeks then health."""
    states = [RELAPSE, RELAPSE] + [HEALTH] * (weeks - 2)
    return pd.DataFrame(
        {
            "patient_id": pd.Series([patient] * weeks, dtype=object),
            "week": pd.Series(range(weeks), dtype=np.int64),
            "state": pd.Series(states, dtype=np.int64),
        }
    )


def test_the_phase_row_allows_the_week_the_top_bin_edge_of_figure_3_adds(
    weekly: pd.DataFrame,
) -> None:
    # The top bin edge of Figure 3 sits one week above the printed maximum of the
    # relapsing-remitting phase, and a drawn follow up window is rounded up to
    # whole weeks, so a draw inside that last week becomes a record one week
    # longer than the printed maximum. The row allows that week, because a
    # failure there would be the arithmetic of the bin edges and not anything
    # about the record. The patient is added at the end so that the frame stays
    # sorted by identifier, as the schema asks.
    longest = int(PAPER.fig3_bin_edges_weeks.value[-1])
    assert longest == PAPER.rr_phase_max_weeks.value + 1
    frame = pd.concat([weekly, one_record("p9999", longest)], ignore_index=True)
    table = reproduction_table(frame)
    row = table[table["quantity"].str.startswith("relapsing-remitting")].iloc[0]
    assert row["reproduced"][1] == float(longest)
    assert row["within_tolerance"] is True


def relapse_only_weekly() -> pd.DataFrame:
    """Return a weekly record in which nobody ever reaches remission."""
    return pd.DataFrame(
        {
            "patient_id": pd.Series(["p0001"] * 4, dtype=object),
            "week": pd.Series(range(4), dtype=np.int64),
            "state": pd.Series([RELAPSE] * 4, dtype=np.int64),
        }
    )


def test_the_closing_table_refuses_a_record_with_only_one_state() -> None:
    with pytest.raises(ValueError, match="remission run"):
        reproduction_table(relapse_only_weekly())


def few_onset_weekly(patients: int = 2, weeks: int = 20) -> pd.DataFrame:
    """Return a weekly record of two relapses per patient, too few to read a period.

    Every patient opens in relapse, recovers, relapses once more and stays in
    health to the end, which leaves two complete relapse durations and one
    complete remission duration per patient and two relapse onsets, one short of
    the three the periodogram of the pooled test needs.
    """
    states = [RELAPSE] * 2 + [HEALTH] * 4 + [RELAPSE] * 2 + [HEALTH] * (weeks - 8)
    return pd.DataFrame(
        {
            "patient_id": pd.Series(
                [f"p{n + 1:04d}" for n in range(patients) for _ in range(weeks)], dtype=object
            ),
            "week": pd.Series(list(range(weeks)) * patients, dtype=np.int64),
            "state": pd.Series(states * patients, dtype=np.int64),
        }
    )


def test_the_closing_table_refuses_a_record_no_periodogram_can_be_read_on() -> None:
    # The periodicity row is the row a small record fails first, and the Raises
    # section of reproduction_table says so: it needs one patient with eight
    # weeks of follow up and three relapse onsets, and a handful of lightly
    # relapsing records carries neither.
    with pytest.raises(ValueError, match="no patient has a record this test can read"):
        reproduction_table(few_onset_weekly())


def test_the_closing_table_refuses_a_record_with_one_complete_duration() -> None:
    # The other requirement the Raises section names: the two goodness of fit
    # rows are fitted on complete durations, and a record whose only remission
    # of each patient runs to the end of the follow up leaves none of them.
    frame = pd.concat([one_record("p0001", 40), one_record("p0002", 40)], ignore_index=True)
    with pytest.raises(ValueError, match="at least two complete durations"):
        reproduction_table(frame)


@pytest.mark.parametrize("alpha", [0.0, 1.0, -0.5])
def test_the_closing_table_refuses_a_significance_level_out_of_range(
    weekly: pd.DataFrame, alpha: float
) -> None:
    with pytest.raises(ValueError, match="alpha must lie"):
        reproduction_table(weekly, alpha=alpha)


def test_the_significance_level_decides_the_goodness_of_fit_rows(weekly: pd.DataFrame) -> None:
    # Both Kolmogorov-Smirnov p values of the shipped twin sit around a half, so
    # a level above them turns those two rows from met to unmet, and no number
    # anywhere in the table moves. This is what alpha is for.
    default = reproduction_table(weekly)
    strict = reproduction_table(weekly, alpha=0.9)
    fits = default["quantity"].str.startswith("exponential fit")
    assert default.loc[fits, "within_tolerance"].tolist() == [True, True]
    assert strict.loc[fits, "within_tolerance"].tolist() == [False, False]
    assert default["reproduced"].tolist() == strict["reproduced"].tolist()


def test_the_periodicity_row_is_judged_against_the_claim_of_the_article(
    weekly: pd.DataFrame,
) -> None:
    # The article reports no periodicity of relapses, and the row says whether
    # this record bears that out: the pooled p value of the onset periodogram
    # above the level the table is built at.
    row = reproduction_table(weekly).iloc[-1]
    assert "periodicity" in str(row["quantity"])
    assert "0.05" in str(row["tolerance"])
    assert row["within_tolerance"] is (float(row["reproduced"]) > 0.05)
    assert row["within_tolerance"] is True


def test_every_row_of_the_closing_table_carries_a_rule(weekly: pd.DataFrame) -> None:
    table = reproduction_table(weekly)
    assert table["tolerance"].notna().all()
    assert table["within_tolerance"].notna().all()


def goodness_of_fit(table: pd.DataFrame) -> pd.Series:
    """Return the mask of the two goodness of fit rows of a closing table."""
    return table["quantity"].str.startswith(GOODNESS_OF_FIT_ROWS)


def ks_test_of_each_state(durations: pd.DataFrame) -> dict[int, fit.TestResult]:
    """Return the Kolmogorov-Smirnov reading of each state, as the table asks for it."""
    return {
        state: fit.test_memoryless(durations, state, method="ks", rng=SYNTHETIC_SEED)
        for state in (RELAPSE, HEALTH)
    }


def test_one_record_gives_one_table_when_no_generator_is_named(weekly: pd.DataFrame) -> None:
    # The bootstrap behind the two goodness of fit rows is the only random step
    # of the table, and a caller who names no generator gets the seed this module
    # fixes, so two builds of the same record are one table.
    first = reproduction_table(weekly)
    second = reproduction_table(weekly)
    assert first["reproduced"].tolist() == second["reproduced"].tolist()


def test_the_generator_the_table_uses_by_default_is_the_seed_of_the_twin(
    weekly: pd.DataFrame,
) -> None:
    # What "no generator named" means, spelled out: the seed the shipped twin was
    # generated from, which is the one this module fixes for the bootstrap.
    named = reproduction_table(weekly, rng=SYNTHETIC_SEED)
    assert named["reproduced"].tolist() == reproduction_table(weekly)["reproduced"].tolist()


def test_the_generator_moves_the_two_goodness_of_fit_rows_and_nothing_else(
    weekly: pd.DataFrame,
) -> None:
    # Two fixed seeds, so the comparison is a fixed one: the bootstrap p values
    # move with the generator, which is what the argument is for, and every other
    # row is a measurement of the record and cannot move at all.
    one = reproduction_table(weekly, rng=1)
    two = reproduction_table(weekly, rng=2)
    fits = goodness_of_fit(one)
    assert one.loc[fits, "reproduced"].tolist() != two.loc[fits, "reproduced"].tolist()
    assert one.loc[~fits, "reproduced"].tolist() == two.loc[~fits, "reproduced"].tolist()


def test_a_generator_is_accepted_where_a_seed_is(weekly: pd.DataFrame) -> None:
    first = reproduction_table(weekly, rng=np.random.default_rng(4))
    second = reproduction_table(weekly, rng=np.random.default_rng(4))
    assert first["reproduced"].tolist() == second["reproduced"].tolist()


def test_a_precomputed_goodness_of_fit_test_is_read_rather_than_measured_again(
    weekly: pd.DataFrame, durations: pd.DataFrame
) -> None:
    # A caller that has already run the test on these durations hands it in, and
    # the table reports that p value rather than drawing a bootstrap of its own.
    planted = {
        state: dataclasses.replace(result, p_value=PLANTED_P_VALUE)
        for state, result in ks_test_of_each_state(durations).items()
    }
    table = reproduction_table(weekly, ks_tests=planted)
    fits = goodness_of_fit(table)
    assert table.loc[fits, "reproduced"].tolist() == [PLANTED_P_VALUE, PLANTED_P_VALUE]
    assert table.loc[fits, "within_tolerance"].tolist() == [False, False]


def test_a_precomputed_test_missing_a_state_is_refused(
    weekly: pd.DataFrame, durations: pd.DataFrame
) -> None:
    tests = ks_test_of_each_state(durations)
    with pytest.raises(ValueError, match="holds no test of state"):
        reproduction_table(weekly, ks_tests={RELAPSE: tests[RELAPSE]})


def test_a_precomputed_test_of_another_reading_is_refused(
    weekly: pd.DataFrame, durations: pd.DataFrame
) -> None:
    # The row reports a Kolmogorov-Smirnov p value and says so in its name, so a
    # reading of another kind cannot stand in for one.
    other = {
        state: fit.test_memoryless(durations, state, method="ad", rng=SYNTHETIC_SEED)
        for state in (RELAPSE, HEALTH)
    }
    with pytest.raises(ValueError, match="method 'ad'"):
        reproduction_table(weekly, ks_tests=other)


def test_a_precomputed_test_measured_on_another_record_is_refused(
    weekly: pd.DataFrame, durations: pd.DataFrame
) -> None:
    # A result carried over from another cohort would put a p value in the table
    # that belongs to no record in it, so the count of durations behind it has to
    # be the count this record holds.
    stale = {
        state: dataclasses.replace(result, n=result.n + 1)
        for state, result in ks_test_of_each_state(durations).items()
    }
    with pytest.raises(ValueError, match="complete duration"):
        reproduction_table(weekly, ks_tests=stale)


def test_a_precomputed_periodicity_result_is_read_rather_than_measured_again(
    weekly: pd.DataFrame,
) -> None:
    measured = fit.test_periodicity(weekly, method="fisher_g")
    planted = dataclasses.replace(
        measured, pooled=dataclasses.replace(measured.pooled, p_value=PLANTED_P_VALUE)
    )
    row = reproduction_table(weekly, periodicity=planted).iloc[-1]
    assert row["reproduced"] == PLANTED_P_VALUE
    assert row["within_tolerance"] is False


def test_a_periodicity_result_measured_on_another_record_is_refused(
    weekly: pd.DataFrame,
) -> None:
    other = weekly[weekly["patient_id"] != weekly["patient_id"].iloc[0]].reset_index(drop=True)
    measured = fit.test_periodicity(other, method="fisher_g")
    with pytest.raises(ValueError, match="another record"):
        reproduction_table(weekly, periodicity=measured)
